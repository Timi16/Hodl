#!/usr/bin/env bash
# Deploys hodl-escrow to Stellar Testnet and regenerates the TypeScript client.
#
#   scripts/deploy.sh
#
# Env overrides: NETWORK (testnet), SOURCE (deployer), USDC_ISSUER (Circle Testnet).
# Writes deployments/<network>.env with every public value the web app needs.
set -euo pipefail

NETWORK="${NETWORK:-testnet}"
SOURCE="${SOURCE:-deployer}"
USDC_ISSUER="${USDC_ISSUER:-GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5}"
WASM="target/wasm32v1-none/release/hodl_escrow.wasm"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

step() { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }

command -v stellar >/dev/null || {
  echo "stellar CLI not found. Install: brew install stellar-cli" >&2
  exit 1
}

# 1. Deployer identity, funded by Friendbot.
step "Deployer identity ($SOURCE)"
if ! stellar keys address "$SOURCE" >/dev/null 2>&1; then
  stellar keys generate "$SOURCE" --network "$NETWORK" --fund
else
  # Re-fund after a Testnet reset; harmless if the account already exists.
  stellar keys fund "$SOURCE" --network "$NETWORK" >/dev/null 2>&1 || true
fi
ADMIN="$(stellar keys address "$SOURCE")"
echo "admin: $ADMIN"

# 2. USDC Stellar Asset Contract id. Deploy the SAC if this network lacks it.
step "USDC Stellar Asset Contract"
USDC_ASSET="USDC:$USDC_ISSUER"
USDC_SAC_ID="$(stellar contract id asset --asset "$USDC_ASSET" --network "$NETWORK")"
stellar contract asset deploy --asset "$USDC_ASSET" \
  --source "$SOURCE" --network "$NETWORK" >/dev/null 2>&1 || true
echo "usdc sac: $USDC_SAC_ID"

# 3. Build and deploy with constructor args.
step "Build"
stellar contract build --package hodl-escrow
test -f "$WASM" || {
  echo "Expected $WASM. Set WASM to the path 'stellar contract build' printed." >&2
  exit 1
}

step "Deploy"
HODL_CONTRACT_ID="$(
  stellar contract deploy \
    --wasm "$WASM" \
    --source "$SOURCE" --network "$NETWORK" \
    --alias hodl-escrow \
    -- --admin "$ADMIN" --usdc "$USDC_SAC_ID"
)"
echo "hodl-escrow: $HODL_CONTRACT_ID"

# Sanity check: the constructor ran and USDC is allowlisted.
ALLOWED="$(stellar contract invoke --id "$HODL_CONTRACT_ID" \
  --source "$SOURCE" --network "$NETWORK" --send=no \
  -- is_token_allowed --token "$USDC_SAC_ID")"
[ "$ALLOWED" = "true" ] || {
  echo "USDC is not allowlisted on the new contract (got: $ALLOWED)" >&2
  exit 1
}

# 4. Record the deployment and regenerate the TypeScript client.
mkdir -p deployments
cat >"deployments/$NETWORK.env" <<EOF
# Generated by scripts/deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). All values are public.
NEXT_PUBLIC_STELLAR_NETWORK=$NETWORK
NEXT_PUBLIC_NETWORK_PASSPHRASE=Test SDF Network ; September 2015
NEXT_PUBLIC_RPC_URL=https://soroban-testnet.stellar.org
NEXT_PUBLIC_HORIZON_URL=https://horizon-testnet.stellar.org
NEXT_PUBLIC_HODL_CONTRACT_ID=$HODL_CONTRACT_ID
NEXT_PUBLIC_USDC_SAC_ID=$USDC_SAC_ID
NEXT_PUBLIC_USDC_ISSUER=$USDC_ISSUER
NEXT_PUBLIC_EXPLORER_URL=https://stellar.expert/explorer/testnet
HODL_ADMIN=$ADMIN
EOF

step "TypeScript bindings"
NETWORK="$NETWORK" "$ROOT/scripts/bindings.sh" "$HODL_CONTRACT_ID"

step "Done"
echo "Contract:  $HODL_CONTRACT_ID"
echo "Explorer:  https://stellar.expert/explorer/$NETWORK/contract/$HODL_CONTRACT_ID"
echo "Env file:  deployments/$NETWORK.env"
